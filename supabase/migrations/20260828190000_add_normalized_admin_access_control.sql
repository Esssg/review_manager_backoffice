create or replace function public.update_admin_setting(
  p_actor_admin_id text,
  p_setting_key text,
  p_scope_type text,
  p_scope_id text default null,
  p_value jsonb default null,
  p_remove boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor public.admins%rowtype;
  v_definition public.settings_definitions%rowtype;
  v_scope_type text := lower(nullif(btrim(p_scope_type), ''));
  v_scope_id text := nullif(btrim(p_scope_id), '');
  v_previous_value jsonb;
  v_numeric_value numeric;
begin
  select * into v_actor
  from public.admins
  where login_id = p_actor_admin_id
    and coalesce(is_active, true) = true;

  if not found then
    raise exception '관리자 정보를 찾지 못했습니다.' using errcode = '28000';
  end if;

  select * into v_definition
  from public.settings_definitions
  where key = p_setting_key;

  if not found then
    raise exception '알 수 없는 설정 항목입니다.' using errcode = '22023';
  end if;

  if v_scope_type not in ('company', 'role', 'admin') then
    raise exception '설정 저장 범위가 올바르지 않습니다.' using errcode = '22023';
  end if;

  if v_scope_type = 'company' and v_scope_id is null then
    v_scope_id := v_actor.company_id::text;
  elsif v_scope_type = 'role' and v_scope_id is null then
    v_scope_id := v_actor.role;
  elsif v_scope_type = 'admin' and v_scope_id is null then
    v_scope_id := v_actor.login_id;
  end if;

  if v_scope_id is null or not (v_scope_type = any(v_definition.allowed_scopes)) then
    raise exception '이 설정을 해당 범위에 저장할 수 없습니다.' using errcode = '42501';
  end if;

  if v_scope_type = 'company' then
    if v_actor.role not in ('developer', 'company_admin')
      or (v_actor.role = 'company_admin' and v_scope_id <> v_actor.company_id::text) then
      raise exception '회사 설정을 변경할 권한이 없습니다.' using errcode = '42501';
    end if;
  elsif v_scope_type = 'role' and v_actor.role <> 'developer' then
    raise exception '역할 기본값을 변경할 권한이 없습니다.' using errcode = '42501';
  elsif v_scope_type = 'admin'
    and v_actor.role <> 'developer'
    and v_scope_id <> v_actor.login_id then
    raise exception '다른 계정의 개인 설정을 변경할 권한이 없습니다.' using errcode = '42501';
  end if;

  select value into v_previous_value
  from public.settings_values
  where setting_key = v_definition.key
    and scope_type = v_scope_type
    and scope_id = v_scope_id;

  if p_remove then
    delete from public.settings_values
    where setting_key = v_definition.key
      and scope_type = v_scope_type
      and scope_id = v_scope_id;

    insert into public.admin_change_audits (
      actor_admin_id,
      target_admin_id,
      company_id,
      event_type,
      before_value,
      after_value,
      metadata
    )
    values (
      v_actor.login_id,
      case when v_scope_type = 'admin' then v_scope_id else null end,
      v_actor.company_id,
      'setting.override.remove',
      v_previous_value,
      null,
      jsonb_build_object('settingKey', v_definition.key, 'scopeType', v_scope_type, 'scopeId', v_scope_id)
    );

    return jsonb_build_object('key', v_definition.key, 'scopeType', v_scope_type, 'scopeId', v_scope_id, 'removed', true);
  end if;

  if p_value is null or jsonb_typeof(p_value) = 'null' then
    if not v_definition.nullable then
      raise exception '필수 설정값을 비울 수 없습니다.' using errcode = '22023';
    end if;
  elsif v_definition.value_type = 'integer' then
    if jsonb_typeof(p_value) <> 'number' then
      raise exception '정수 설정값이 올바르지 않습니다.' using errcode = '22023';
    end if;
    v_numeric_value := (p_value #>> '{}')::numeric;
    if v_numeric_value <> trunc(v_numeric_value)
      or (v_definition.min_value is not null and v_numeric_value < v_definition.min_value)
      or (v_definition.max_value is not null and v_numeric_value > v_definition.max_value) then
      raise exception '설정값 범위를 벗어났습니다.' using errcode = '22023';
    end if;
  elsif v_definition.value_type = 'enum' then
    if jsonb_typeof(p_value) <> 'string'
      or not ((p_value #>> '{}') = any(v_definition.allowed_values)) then
      raise exception '허용되지 않은 선택값입니다.' using errcode = '22023';
    end if;
  elsif v_definition.value_type = 'boolean' and jsonb_typeof(p_value) <> 'boolean' then
    raise exception 'boolean 설정값이 올바르지 않습니다.' using errcode = '22023';
  elsif v_definition.value_type = 'string' and jsonb_typeof(p_value) <> 'string' then
    raise exception '문자열 설정값이 올바르지 않습니다.' using errcode = '22023';
  end if;

  insert into public.settings_values (
    setting_key,
    scope_type,
    scope_id,
    value,
    updated_by
  )
  values (
    v_definition.key,
    v_scope_type,
    v_scope_id,
    p_value,
    v_actor.login_id
  )
  on conflict (setting_key, scope_type, scope_id)
  do update set
    value = excluded.value,
    updated_by = excluded.updated_by,
    updated_at = now();

  insert into public.admin_change_audits (
    actor_admin_id,
    target_admin_id,
    company_id,
    event_type,
    before_value,
    after_value,
    metadata
  )
  values (
    v_actor.login_id,
    case when v_scope_type = 'admin' then v_scope_id else null end,
    v_actor.company_id,
    'setting.update',
    v_previous_value,
    p_value,
    jsonb_build_object('settingKey', v_definition.key, 'scopeType', v_scope_type, 'scopeId', v_scope_id)
  );

  return jsonb_build_object(
    'key', v_definition.key,
    'scopeType', v_scope_type,
    'scopeId', v_scope_id,
    'value', p_value,
    'removed', false
  );
end;
$$;

revoke all on function public.update_admin_setting(text, text, text, text, jsonb, boolean) from public;
revoke all on function public.update_admin_setting(text, text, text, text, jsonb, boolean) from anon;
revoke all on function public.update_admin_setting(text, text, text, text, jsonb, boolean) from authenticated;
