-- 호출하지 않으며, 함수 실행 권한도 service_role로 제한한다.
create or replace function public.get_admin_access_bundle(p_admin_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin public.admins%rowtype;
  v_permissions jsonb;
  v_menu_permissions jsonb;
  v_settings jsonb;
begin
  select *
  into v_admin
  from public.admins
  where login_id = p_admin_id
    and coalesce(is_active, true) = true;

  if not found then
    raise exception '관리자 정보를 찾지 못했습니다.' using errcode = '28000';
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', bindings.id,
        'permissionCode', bindings.permission_code,
        'effect', bindings.effect,
        'dataScope', bindings.data_scope,
        'subjectType', bindings.subject_type,
        'subjectId', bindings.subject_id,
        'priority', bindings.priority
      )
      order by bindings.permission_code, bindings.subject_type, bindings.priority
    ),
    '[]'::jsonb
  )
  into v_permissions
  from public.permission_bindings as bindings
  where bindings.subject_type = 'global'
    or (bindings.subject_type = 'company' and bindings.subject_id = v_admin.company_id::text)
    or (bindings.subject_type = 'role' and lower(bindings.subject_id) = lower(v_admin.role))
    or (bindings.subject_type = 'admin' and bindings.subject_id = v_admin.login_id);

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'admin_id', v_admin.login_id,
        'menu_number', case bindings.permission_code
          when 'menu.dashboard' then 1
          when 'menu.product' then 2
          when 'menu.review_receive' then 3
          when 'menu.product_overview' then 4
          when 'menu.export' then 5
          when 'menu.file_upload' then 6
          when 'menu.bulk_edit' then 7
        end,
        'permission_code', bindings.permission_code,
        'effect', bindings.effect,
        'data_scope', bindings.data_scope
      )
      order by case bindings.permission_code
        when 'menu.dashboard' then 1
        when 'menu.product' then 2
        when 'menu.review_receive' then 3
        when 'menu.product_overview' then 4
        when 'menu.export' then 5
        when 'menu.file_upload' then 6
        when 'menu.bulk_edit' then 7
        else 99
      end
    ),
    '[]'::jsonb
  )
  into v_menu_permissions
  from public.permission_bindings as bindings
  where bindings.effect = 'allow'
    and bindings.permission_code in (
      'menu.dashboard',
      'menu.product',
      'menu.review_receive',
      'menu.product_overview',
      'menu.export',
      'menu.file_upload',
      'menu.bulk_edit'
    )
    and (
      bindings.subject_type = 'global'
      or (bindings.subject_type = 'company' and bindings.subject_id = v_admin.company_id::text)
      or (bindings.subject_type = 'role' and lower(bindings.subject_id) = lower(v_admin.role))
      or (bindings.subject_type = 'admin' and bindings.subject_id = v_admin.login_id)
    );

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'key', definitions.key,
        'value', coalesce(resolved.value, definitions.default_value),
        'source', coalesce(resolved.scope_type, 'definition'),
        'hasOverride', resolved.scope_type = 'admin'
      )
      order by definitions.key
    ),
    '[]'::jsonb
  )
  into v_settings
  from public.settings_definitions as definitions
  left join lateral (
    select setting_values.value, setting_values.scope_type
    from public.settings_values as setting_values
    where setting_values.setting_key = definitions.key
      and (
        (setting_values.scope_type = 'company' and setting_values.scope_id = v_admin.company_id::text)
        or (setting_values.scope_type = 'role' and lower(setting_values.scope_id) = lower(v_admin.role))
        or (setting_values.scope_type = 'admin' and setting_values.scope_id = v_admin.login_id)
      )
    order by case setting_values.scope_type when 'company' then 1 when 'role' then 2 when 'admin' then 3 else 0 end desc
    limit 1
  ) as resolved on true;

  return jsonb_build_object(
    'principal', jsonb_build_object(
      'adminId', v_admin.login_id,
      'companyId', v_admin.company_id,
      'role', v_admin.role
    ),
    'profile', jsonb_build_object(
      'loginId', v_admin.login_id,
      'username', v_admin.username,
      'email', v_admin.email,
      'company', v_admin.company,
      'companyId', v_admin.company_id,
      'role', v_admin.role,
      'isActive', coalesce(v_admin.is_active, true)
    ),
    'role', v_admin.role,
    'companyId', v_admin.company_id,
    'capabilities', jsonb_build_object(
      'includeCompanyDataInclude', case
        when v_admin.role = 'developer' then true
        else coalesce(v_admin.include_company_data_include, false)
      end,
      'canVerifyDeposit', coalesce(v_admin.can_verify_deposit, true)
    ),
    'permissions', v_permissions,
    'permissionBindings', v_permissions,
    'menuPermissions', v_menu_permissions,
    'settings', v_settings
  );
end;
$$;

