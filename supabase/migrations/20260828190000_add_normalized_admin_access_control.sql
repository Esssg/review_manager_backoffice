-- 실수로 제거하지 않도록 DB 수준에서 보호한다.
create or replace function public.prevent_last_active_developer_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_other_developer_count integer;
begin
  if TG_OP = 'DELETE' then
    if old.role <> 'developer' then
      return old;
    end if;
  elsif old.role = 'developer'
    and (new.role is distinct from 'developer' or coalesce(new.is_active, true) = false) then
    null;
  else
    return new;
  end if;

  if old.role = 'developer' then
    select count(*)
    into v_other_developer_count
    from public.admins as admins
    where admins.login_id <> old.login_id
      and admins.role = 'developer'
      and coalesce(admins.is_active, true) = true;

    if v_other_developer_count = 0 then
      raise exception '활성 developer는 최소 1명 이상 유지해야 합니다.' using errcode = '23514';
    end if;
  end if;

  return case when TG_OP = 'DELETE' then old else new end;
end;
$$;

