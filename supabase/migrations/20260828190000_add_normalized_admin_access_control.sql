-- 개인 권한은 한 계정·권한 코드당 하나의 명시적 override만 유지한다.
-- p_remove=true이면 상위 회사/역할 기본값을 다시 상속한다.
create or replace function public.update_admin_permission(
  p_actor_admin_id text,
  p_target_admin_id text,
  p_permission_code text,
  p_effect text default null,
  p_data_scope text default 'personal',
  p_remove boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor public.admins%rowtype;
  v_target public.admins%rowtype;
  v_definition public.permission_definitions%rowtype;
  v_effect text := lower(nullif(btrim(p_effect), ''));
  v_data_scope text := lower(nullif(btrim(p_data_scope), ''));
  v_previous jsonb;
begin
  select * into v_actor
  from public.admins
  where login_id = p_actor_admin_id
    and coalesce(is_active, true) = true;

  if not found then
    raise exception '관리자 정보를 찾지 못했습니다.' using errcode = '28000';
  end if;

  select * into v_target
  from public.admins
  where login_id = p_target_admin_id
    and coalesce(is_active, true) = true;

  if not found then
    raise exception '대상 임직원을 찾지 못했습니다.' using errcode = '22023';
  end if;

  if v_actor.role <> 'developer'
    and not (
      v_actor.role = 'company_admin'
      and v_target.role = 'employee'
      and v_actor.company_id = v_target.company_id
    ) then
    raise exception '해당 계정의 권한을 변경할 수 없습니다.' using errcode = '42501';
  end if;

  select * into v_definition
  from public.permission_definitions
  where code = p_permission_code;

  if not found then
    raise exception '알 수 없는 권한 코드입니다.' using errcode = '22023';
  end if;

  if p_remove then
    select jsonb_agg(to_jsonb(bindings)) into v_previous
    from public.permission_bindings as bindings
    where bindings.subject_type = 'admin'
      and bindings.subject_id = v_target.login_id
      and bindings.permission_code = v_definition.code;

    delete from public.permission_bindings
    where subject_type = 'admin'
      and subject_id = v_target.login_id
      and permission_code = v_definition.code;

    insert into public.admin_change_audits (
      actor_admin_id,
      target_admin_id,
      company_id,
      event_type,
      before_value,
      after_value,
      metadata
    )
    values (
      v_actor.login_id,
      v_target.login_id,
      v_target.company_id,
      'permission.override.remove',
      v_previous,
      null,
      jsonb_build_object('permissionCode', v_definition.code)
    );

    return jsonb_build_object(
      'targetAdminId', v_target.login_id,
      'permissionCode', v_definition.code,
      'removed', true
    );
  end if;

  if v_effect not in ('allow', 'deny')
    or v_data_scope not in ('personal', 'company', 'all') then
    raise exception '권한 효과 또는 데이터 범위가 올바르지 않습니다.' using errcode = '22023';
  end if;

  select to_jsonb(bindings) into v_previous
  from public.permission_bindings as bindings
  where bindings.subject_type = 'admin'
    and bindings.subject_id = v_target.login_id
    and bindings.permission_code = v_definition.code
  order by bindings.priority desc, bindings.id desc
  limit 1;

  delete from public.permission_bindings
  where subject_type = 'admin'
    and subject_id = v_target.login_id
    and permission_code = v_definition.code;

  insert into public.permission_bindings (
    subject_type,
    subject_id,
    permission_code,
    effect,
    data_scope
  )
  values (
    'admin',
    v_target.login_id,
    v_definition.code,
    v_effect,
    v_data_scope
  );

  insert into public.admin_change_audits (
    actor_admin_id,
    target_admin_id,
    company_id,
    event_type,
    before_value,
    after_value,
    metadata
  )
  values (
    v_actor.login_id,
    v_target.login_id,
    v_target.company_id,
    'permission.override.update',
    v_previous,
    jsonb_build_object(
      'effect', v_effect,
      'dataScope', v_data_scope
    ),
    jsonb_build_object('permissionCode', v_definition.code)
  );

  return jsonb_build_object(
    'targetAdminId', v_target.login_id,
    'permissionCode', v_definition.code,
    'effect', v_effect,
    'dataScope', v_data_scope,
    'removed', false
  );
end;
$$;

