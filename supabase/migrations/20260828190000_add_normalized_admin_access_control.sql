-- 개발자와 company_admin이 관리할 수 있는 임직원 목록과 개인 권한을
-- 하나의 서버 응답으로 반환한다. 역할·회사 범위는 여기서 다시 확인한다.
create or replace function public.get_admin_members(p_actor_admin_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor public.admins%rowtype;
  v_members jsonb;
begin
  select * into v_actor
  from public.admins
  where login_id = p_actor_admin_id
    and coalesce(is_active, true) = true;

  if not found then
    raise exception '관리자 정보를 찾지 못했습니다.' using errcode = '28000';
  end if;

  if v_actor.role not in ('developer', 'company_admin') then
    raise exception '임직원 관리 권한이 없습니다.' using errcode = '42501';
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'loginId', members.login_id,
        'username', members.username,
        'email', members.email,
        'company', members.company,
        'companyId', members.company_id,
        'role', members.role,
        'isActive', coalesce(members.is_active, true),
        'permissions', coalesce(
          (
            select jsonb_agg(
              jsonb_build_object(
                'id', bindings.id,
                'permissionCode', bindings.permission_code,
                'effect', bindings.effect,
                'dataScope', bindings.data_scope,
                'subjectType', bindings.subject_type,
                'subjectId', bindings.subject_id,
                'priority', bindings.priority
              )
              order by bindings.permission_code, bindings.priority
            )
            from public.permission_bindings as bindings
            where bindings.subject_type = 'global'
              or (bindings.subject_type = 'company' and bindings.subject_id = members.company_id::text)
              or (bindings.subject_type = 'role' and lower(bindings.subject_id) = lower(members.role))
              or (bindings.subject_type = 'admin' and bindings.subject_id = members.login_id)
          ),
          '[]'::jsonb
        )
      )
      order by members.company, members.login_id
    ),
    '[]'::jsonb
  )
  into v_members
  from public.admins as members
  where coalesce(members.is_active, true) = true
    and (
      v_actor.role = 'developer'
      or (
        members.role = 'employee'
        and members.company_id = v_actor.company_id
      )
    );

  return v_members;
end;
$$;

