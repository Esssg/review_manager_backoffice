    email = case when p_payload ? 'email' then nullif(btrim(p_payload ->> 'email'), '') else email end,
    password = case when p_payload ? 'password' then p_payload ->> 'password' else password end
  where login_id = v_admin.login_id;

  select * into v_admin from public.admins where login_id = p_actor_admin_id;

  return jsonb_build_object(
    'loginId', v_admin.login_id,
    'username', v_admin.username,
    'phone_number', v_admin.phone_number,
    'email', v_admin.email,
    'company', v_admin.company,
    'companyId', v_admin.company_id,
    'role', v_admin.role
  );
end;
